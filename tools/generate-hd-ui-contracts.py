def validate_theme(theme):
    if theme.get("schema") != 1:
        fail("hd-ui-theme.json: schema must be 1")
    if not isinstance(theme.get("version"), str) or not VERSION_RE.match(theme.get("version", "")):
        fail("hd-ui-theme.json: version string required (^[A-Za-z0-9._-]+$)")
    colors = theme.get("colors")
    if not isinstance(colors, dict) or not colors:
        fail("hd-ui-theme.json: colors object required")
    for name, value in colors.items():
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("hd-ui-theme.json: color " + name + " must be packed RRGGBBAA")
    dlg = theme.get("dialog") or {}
    if dlg.get("radiusPx", 0) <= 0 or dlg.get("borderWidthPx", 0) <= 0:
        fail("hd-ui-theme.json: dialog.radiusPx/borderWidthPx must be > 0")
    shadow = theme.get("shadow") or {}
    halo = theme.get("halo") or {}
    if shadow.get("glowRadiusPx", 0) <= 0 or halo.get("glowRadiusPx", 0) <= 0:
        fail("hd-ui-theme.json: shadow/halo glowRadiusPx must be > 0")
    typography = theme.get("typography") or {}
    for key in ("titleFontSizeScale", "bodyFontSizeScale", "bodyLineHeight",
                "labelFontSizeScaleWide", "labelFontSizeScaleCompact",
                "bodyFontSizeScaleWide", "bodyFontSizeScaleCompact",
                "bodyFontWidthScaleWide", "bodyFontWidthScaleCompact",
                "bodyWrapMeasureScaleWide", "bodyWrapMeasureScaleCompact",
                "bodyProjectionLineHeightScaleWide", "bodyProjectionLineHeightScaleCompact"):
        if not isinstance(typography.get(key), (int, float)) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be > 0")
    for key in ("labelFontSizePx", "bodyFontSizePx", "titleFontWeight", "labelFontWeight", "bodyFontWeight",
                "buttonPrimaryLineHeightPx", "buttonSecondaryLineHeightPx",
                "buttonLabelGapPx", "buttonLabelPaddingYPx", "buttonSecondaryFontSizePx"):
        if not isinstance(typography.get(key), int) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be a positive integer")
    secondary_opacity = typography.get("buttonSecondaryOpacity")
    if (not isinstance(secondary_opacity, (int, float))
            or not 0.0 < secondary_opacity <= 1.0):
        fail("hd-ui-theme.json: typography.buttonSecondaryOpacity must be in (0, 1]")
    f21_type = theme.get("f21Typography") or {}
    for key in ("protocolWidePx", "protocolCompactPx", "titleWidePx", "titleCompactPx",
                "dataWidePx", "dataCompactPx", "bodyWidePx", "bodyCompactPx",
                "inputWidePx", "inputCompactPx", "actionWidePx", "actionCompactPx"):
        if not isinstance(f21_type.get(key), int) or f21_type[key] <= 0:
            fail("hd-ui-theme.json: f21Typography." + key + " must be a positive integer")
    if (not isinstance(f21_type.get("bodyLineHeight"), (int, float))
            or f21_type["bodyLineHeight"] <= 1.0):
        fail("hd-ui-theme.json: f21Typography.bodyLineHeight must be > 1")
    f21_safe = theme.get("f21TextSafeArea") or {}
    for key in ("protocolInsetXWidePx", "protocolInsetXCompactPx",
                "protocolInsetYWidePx", "protocolInsetYCompactPx",
                "minimumHorizontalPaddingPx", "minimumVerticalPaddingPx"):
        if not isinstance(f21_safe.get(key), int) or f21_safe[key] < 4:
            fail("hd-ui-theme.json: f21TextSafeArea." + key + " must be an integer >= 4")
    command_action = theme.get("commandAction") or {}
    for key in COMMAND_ACTION_COLOR_KEYS:
        value = command_action.get(key)
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("hd-ui-theme.json: commandAction." + key + " must be packed RRGGBBAA")
    for key in COMMAND_ACTION_GLOW_RADIUS_KEYS:
        if not isinstance(command_action.get(key), (int, float)) or command_action[key] <= 0:
            fail("hd-ui-theme.json: commandAction." + key + " must be > 0")
    if not isinstance(command_action.get("radiusPx"), (int, float)) or command_action["radiusPx"] <= 0:
        fail("hd-ui-theme.json: commandAction.radiusPx must be > 0")
    if command_action.get("hoverGlowRadiusPx", 0) <= command_action.get("restGlowRadiusPx", 1):
        fail("hd-ui-theme.json: commandAction.hoverGlowRadiusPx must read stronger than rest")
    if command_action.get("pressedGlowRadiusPx", 1) >= command_action.get("restGlowRadiusPx", 0):
        fail("hd-ui-theme.json: commandAction.pressedGlowRadiusPx must read tighter than rest")


def validate_f33(f33):
    if f33.get("schema") != 1:
        fail("f33-abandon.json: schema must be 1")
    if not isinstance(f33.get("version"), str) or not f33["version"]:
        fail("f33-abandon.json: version string required")
    form = f33.get("form") or {}
    if (form.get("id") != "f33-abandon" or form.get("familyId") != 33
            or form.get("archetype") != "small-confirmation"
            or form.get("source") != "FormConfigs/f33-abandon.json"):
        fail("f33-abandon.json: generated form identity/provenance is invalid")
    icon = form.get("icon") or {}
    if icon != {"kind": "warning", "glyph": "!", "tone": "warning"}:
        fail("f33-abandon.json: generated warning icon metadata drifted")
    buttons = form.get("buttons")
    if not isinstance(buttons, list) or len(buttons) != 2:
        fail("f33-abandon.json: generated form requires two button descriptors")
    expected_buttons = (("cancel", "KEEP PLAYING", "safe", "cancel"),
                        ("confirm", "ABANDON GAME", "danger", "confirm"))
    for button, expected in zip(buttons, expected_buttons):
        if tuple(button.get(key) for key in ("id", "label", "tone", "action")) != expected:
            fail("f33-abandon.json: generated button metadata drifted")
        button_style = button.get("style") or {}
        for key in ("fill", "border", "text"):
            if not isinstance(button_style.get(key), str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", button_style[key]):
                fail("f33-abandon.json: generated button style " + key + " must be RRGGBBAA")
    copy = f33.get("copy") or {}
    for key in ("protocol", "title", "safeAction", "destructiveAction"):
        if not isinstance(copy.get(key), str) or not copy[key]:
            fail("f33-abandon.json: copy." + key + " string required")
    if (not isinstance(copy.get("message"), list) or len(copy["message"]) != 2
            or not all(isinstance(line, str) and line for line in copy["message"])):
        fail("f33-abandon.json: copy.message must contain exactly two non-empty lines")
    style = f33.get("style") or {}
    if not isinstance(style.get("cutCornerPx"), (int, float)) or style["cutCornerPx"] <= 0:
        fail("f33-abandon.json: style.cutCornerPx must be > 0")
    if (not isinstance(style.get("protocolTextInsetPx"), (int, float))
            or style["protocolTextInsetPx"] <= 0):
        fail("f33-abandon.json: style.protocolTextInsetPx must be > 0")
    if style["protocolTextInsetPx"] != style["cutCornerPx"] + 12:
        fail("f33-abandon.json: protocolTextInsetPx must be two mono cells after cutCornerPx")
    for key in ("panelFillTop", "panelFillBottom", "frame", "protocolText", "divider",
                "footerFill", "footerDot", "warning", "safeFill", "safeBorder",
                "destructiveFill", "destructiveText"):
        value = style.get(key)
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("f33-abandon.json: style." + key + " must be packed RRGGBBAA")
    layouts = f33.get("layouts")
    if not isinstance(layouts, dict) or "wide" not in layouts or "compact" not in layouts:
        fail("f33-abandon.json: explicit wide/compact layouts required")
    for name in ("wide", "compact"):
        l = layouts[name]
        if l.get("designWidth", 0) <= 0 or l.get("designHeight", 0) <= 0:
            fail("f33-abandon.json: " + name + " design canvas required")
        for part in ("window", "status", "warning", "title", "message", "footer", "yes", "no"):
            r = l.get(part)
            if not r or not all(isinstance(r[k], int) for k in ("x", "y", "width", "height")):
                fail("f33-abandon.json: " + name + "." + part + " must be an integer rect")
        button_rects = l.get("buttons") or {}
        if set(button_rects) != {"cancel", "confirm"}:
            fail("f33-abandon.json: " + name + ".buttons must resolve cancel/confirm slots")
        if button_rects["cancel"] != l["no"] or button_rects["confirm"] != l["yes"]:
            fail("f33-abandon.json: " + name + " compatibility button aliases drifted")
        for part in ("yes", "no"):
            if l[part]["width"] < MIN_ACTION_TARGET or l[part]["height"] < MIN_ACTION_TARGET:
                fail("f33-abandon.json: " + name + "." + part
                     + " below the " + str(MIN_ACTION_TARGET) + "x" + str(MIN_ACTION_TARGET)
                     + " action-target floor")

        def contained(inner, outer):
            return (inner["x"] >= outer["x"] and inner["y"] >= outer["y"]
                    and inner["x"] + inner["width"] <= outer["x"] + outer["width"]
                    and inner["y"] + inner["height"] <= outer["y"] + outer["height"])
        if not contained(l["window"], {"x": 0, "y": 0, "width": l["designWidth"], "height": l["designHeight"]}):
            fail("f33-abandon.json: " + name + ".window must fit the design canvas")
        for part in ("status", "warning", "title", "message", "footer", "yes", "no"):
            if not contained(l[part], l["window"]):
                fail("f33-abandon.json: " + name + "." + part + " must be inside the window")
        if (l["yes"]["x"] < l["no"]["x"] + l["no"]["width"] and l["no"]["x"] < l["yes"]["x"] + l["yes"]["width"]
                and l["yes"]["y"] < l["no"]["y"] + l["no"]["height"] and l["no"]["y"] < l["yes"]["y"] + l["yes"]["height"]):
            fail("f33-abandon.json: " + name + ".yes and .no must not overlap")
        if l["yes"]["x"] + l["yes"]["width"] != l["message"]["x"] + l["message"]["width"]:
            fail("f33-abandon.json: " + name + ".yes must end at the message content rail")
    m = f33.get("motion") or {}
    if m.get("durationMs", 0) <= 0 or m.get("durationMs", 0) > 1000:
        fail("f33-abandon.json: motion.durationMs must be in (0, 1000]")
    if not (0.0 < m.get("scaleFrom", 0.0) <= 1.0):
        fail("f33-abandon.json: motion.scaleFrom must be in (0, 1]")
    if m.get("captureModeDurationMs") != 0:
        fail("f33-abandon.json: captureModeDurationMs must be 0 (deterministic captures)")


IDENT_RE = _re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SLUG_RE = _re.compile(r"^[a-z0-9][a-z0-9-]*$")


def load_registry(path):
    if not os.path.isfile(path):
        fail("contract registry missing: " + path)
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def validate_registry(registry):
    if registry.get("schema") != 1:
        fail("hd-ui-contracts.json: schema must be 1")
    entries = registry.get("entries")
    if not isinstance(entries, list) or not entries:
        fail("hd-ui-contracts.json: non-empty entries array required")
    seen = {"id": set(), "contract": set(), "native output": set(), "browser output": set()}
    allowed_emitters = {"theme", "legacy-abandon", "family", "screen"}
    allowed_profiles = {"theme", "legacy-abandon", "family", "command-card",
                        "small-confirmation", "contact-decision",
                        "contact-intel-board", "content-block", "screen",
                        "selection-list", "scrollable-collection"}
    for index, entry in enumerate(entries):
        where = "hd-ui-contracts.json: entries[" + str(index) + "]"
        if not isinstance(entry, dict):
            fail(where + " must be an object")
        contract_id = entry.get("id")
        contract = entry.get("contract")
        emitter = entry.get("emitter")
        profile = entry.get("validationProfile")
        native = entry.get("native") or {}
        browser = entry.get("browser") or {}
        if not isinstance(contract_id, str) or not SLUG_RE.match(contract_id):
            fail(where + ".id must be a lower-kebab identifier")
        if not isinstance(contract, str) or not re.fullmatch(r"[a-z0-9-]+\.json", contract):
            fail(where + ".contract must be a Contracts/*.json basename")
        if emitter not in allowed_emitters or profile not in allowed_profiles:
            fail(where + " has an unsupported emitter or validationProfile")
        if ((emitter == "theme") != (profile == "theme")
                or (emitter == "legacy-abandon") != (profile == "legacy-abandon")):
            fail(where + " emitter and validationProfile are incompatible")
        if (emitter == "screen") != (profile == "screen"):
            fail(where + " screen emitter requires the screen validationProfile")
        for key in ("namespace", "prefix"):
            if not isinstance(native.get(key), str) or not IDENT_RE.match(native[key]):
                fail(where + ".native." + key + " must be a C++ identifier")
        if (not isinstance(native.get("output"), str)
                or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*\.generated\.h", native["output"])):
            fail(where + ".native.output must be a generated header basename")
        if not isinstance(browser.get("global"), str) or not IDENT_RE.match(browser["global"]):
            fail(where + ".browser.global must be a JavaScript identifier")
        if (not isinstance(browser.get("output"), str)
                or not re.fullmatch(r"[a-z0-9-]+\.js", browser["output"])):
            fail(where + ".browser.output must be a generated JavaScript basename")
        if not isinstance(entry.get("rendererOwnership"), str) or not entry["rendererOwnership"]:
            fail(where + ".rendererOwnership must be a non-empty string")
        scenarios = entry.get("harnessScenarioIds")
        if (not isinstance(scenarios, list)
                or any(not isinstance(value, int) or isinstance(value, bool) or value <= 0
                       for value in scenarios)):
            fail(where + ".harnessScenarioIds must contain positive integer ids")
        for label, value in (("id", contract_id), ("contract", contract),
                             ("native output", native["output"]),
                             ("browser output", browser["output"])):
            if value in seen[label]:
                fail(where + " duplicates " + label + " " + value)
            seen[label].add(value)
        if "engineTextCalibration" in entry and not isinstance(entry["engineTextCalibration"], bool):
            fail(where + ".engineTextCalibration must be boolean")
    return entries


def validate_family(doc, rel, profile, engine_text_calibration=False):
    if doc.get("schema") != 1:
        fail(rel + ": schema must be 1")
    if not isinstance(doc.get("version"), str) or not VERSION_RE.match(doc.get("version", "")):
        fail(rel + ": version string required")
    if profile in {"small-confirmation", "contact-decision", "contact-intel-board"}:
        form = doc.get("form") or {}
        if form.get("archetype") != profile or not form.get("id"):
            fail(rel + ": " + profile + " form identity required")
        if doc.get("style") is None or doc.get("layouts") is None:
            fail(rel + ": " + profile + " form must carry style/layouts")
        copy = doc.get("copy") or {}
        for key in ("protocol", "title"):
            if not isinstance(copy.get(key), str) or not copy[key]:
                fail(rel + ": " + profile + " copy." + key + " required")
        message = copy.get("message")
        if not isinstance(message, list) or not all(isinstance(line, str) and line for line in message):
            fail(rel + ": " + profile + " copy.message must be a list of non-empty lines")
        presentation = doc.get("presentation") or {}
        density = presentation.get("density")
        numerator = presentation.get("scaleNumerator")
        denominator = presentation.get("scaleDenominator")
        if density not in ("standard", "brief-acknowledgement"):
            fail(rel + ": generated density profile is invalid")
        if (not isinstance(numerator, int) or not isinstance(denominator, int)
                or numerator <= 0 or denominator <= 0):
            fail(rel + ": generated density scale must be a positive integer ratio")
        if density == "standard" and (numerator, denominator) != (1, 1):
            fail(rel + ": standard density must use scale 1/1")
        if density == "brief-acknowledgement" and (numerator, denominator) != (2, 3):
            fail(rel + ": brief acknowledgement density must use scale 2/3")
        layout_names = (("wide", "compact", "portrait")
                        if profile == "contact-intel-board" else ("wide", "compact"))
        for layout_name in layout_names:
            layout = doc["layouts"].get(layout_name) or {}
            buttons = layout.get("buttons") or {}
            if set(buttons) != {button["id"] for button in form.get("buttons", [])}:
                fail(rel + ": " + layout_name + " generated button geometry is incomplete")
            visible_action_floor = (MIN_ACTION_TARGET * numerator + denominator // 2) // denominator
            for button_id, rect in buttons.items():
                if (rect.get("width", 0) < visible_action_floor
                        or rect.get("height", 0) < visible_action_floor):
                    fail(rel + ": " + layout_name + ".buttons." + button_id
                         + " below the density-scaled " + str(visible_action_floor) + "x"
                         + str(visible_action_floor) + " visible-action floor")
            if form.get("buttons") and profile != "contact-intel-board":
                # Modal archetypes keep the rightmost action on the text rail;
                # the board's corner/stacked cards legitimately break the rail
                # (their geometry policy lives in generate-hd-window-form.py).
                rightmost = buttons[form["buttons"][-1]["id"]]
                message = layout.get("message") or {}
                if (rightmost["x"] + rightmost["width"]
                        != message.get("x", 0) + message.get("width", 0)):
                    fail(rel + ": " + layout_name + " rightmost action left the text rail")
        if profile == "contact-intel-board":
            for button in form.get("buttons", []):
                if "secondaryLabel" in button:
                    secondary = button["secondaryLabel"]
                    if (not isinstance(secondary, str) or not secondary.strip()
                            or len(secondary) > 24
                            or any(ord(char) < 32 for char in secondary)):
                        fail(rel + ": button.secondaryLabel must be one non-empty line of at most 24 characters")
            motion = doc.get("motion") or {}
            sweep_period = motion.get("radarSweepPeriodMs")
            if not isinstance(sweep_period, int) or not 1000 <= sweep_period <= 10000:
                fail(rel + ": motion.radarSweepPeriodMs must be an integer in [1000, 10000]")
            decay_floor = motion.get("radarContactDecayFloor")
            if not isinstance(decay_floor, (int, float)) or not 0.0 <= decay_floor <= 0.5:
                fail(rel + ": motion.radarContactDecayFloor must be in [0, 0.5]")
            decay_exponent = motion.get("radarContactDecayExponent")
            if not isinstance(decay_exponent, (int, float)) or not 1.0 <= decay_exponent <= 6.0:
                fail(rel + ": motion.radarContactDecayExponent must be in [1, 6]")
        return
    if profile == "selection-list":
        form = doc.get("form") or {}
        if form.get("archetype") != "selection-list" or not form.get("id"):
            fail(rel + ": selection-list form identity required")
        if not isinstance(form.get("familyId"), int) or form["familyId"] <= 0:
            fail(rel + ": selection-list familyId must be a positive integer")
        if doc.get("style") is None or doc.get("layouts") is None:
            fail(rel + ": selection-list form must carry style/layouts")
        buttons = form.get("buttons") or []
        if len(buttons) != 1 or buttons[0].get("action") != "cancel":
            fail(rel + ": selection-list requires exactly one cancel button")
        button = buttons[0]
        for key in ("id", "label", "tone", "action"):
            if not isinstance(button.get(key), str) or not button[key]:
                fail(rel + ": selection-list button." + key + " required")
        style = button.get("style") or {}
        for key in ("fill", "border", "text"):
            if not isinstance(style.get(key), str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", style[key]):
                fail(rel + ": selection-list button.style." + key + " must be packed 8-digit RGBA")
        copy = doc.get("copy") or {}
        if not isinstance(copy.get("protocol"), str) or not copy["protocol"]:
            fail(rel + ": selection-list copy.protocol required")
        if not isinstance(copy.get("title"), str) or not copy["title"]:
            fail(rel + ": selection-list copy.title required")
        rows = copy.get("rows")
        if not isinstance(rows, list) or not rows:
            fail(rel + ": selection-list copy.rows must be a non-empty list")
        for index, row in enumerate(rows):
            if not isinstance(row, dict):
                fail(rel + ": selection-list copy.rows[" + str(index) + "] must be an object")
            if not isinstance(row.get("label"), str) or not row["label"]:
                fail(rel + ": selection-list copy.rows[" + str(index) + "].label required")
            if not isinstance(row.get("enabled"), bool):
                fail(rel + ": selection-list copy.rows[" + str(index) + "].enabled must be a boolean")
        presentation = doc.get("presentation") or {}
        if presentation.get("density") != "standard":
            fail(rel + ": selection-list density must be standard")
        if (presentation.get("scaleNumerator"), presentation.get("scaleDenominator")) != (1, 1):
            fail(rel + ": selection-list density must use scale 1/1")
        for layout_name in ("wide", "compact"):
            layout = (doc.get("layouts") or {}).get(layout_name) or {}
            rect = layout.get("list")
            if not rect or not all(isinstance(rect.get(k), int) for k in ("x", "y", "width", "height")):
                fail(rel + ": " + layout_name + " list must be an integer rect")
            row_height = layout.get("rowHeight")
            visible_rows = layout.get("visibleRows")
