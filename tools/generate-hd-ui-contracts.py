def fail(msg):
    print("generate-hd-ui-contracts: error: " + msg, file=sys.stderr)
    sys.exit(1)


def load_json(rel):
    path = os.path.join(CONTRACTS_DIR, rel)
    if not os.path.isfile(path):
        fail("canonical contract missing: " + path)
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


import re as _re

VERSION_RE = _re.compile(r"^[A-Za-z0-9._-]+$")


def validate_theme(theme):
    if theme.get("schema") != 1:
        fail("hd-ui-theme.json: schema must be 1")
    if not isinstance(theme.get("version"), str) or not VERSION_RE.match(theme.get("version", "")):
        fail("hd-ui-theme.json: version string required (^[A-Za-z0-9._-]+$)")
    colors = theme.get("colors")
    if not isinstance(colors, dict) or not colors:
        fail("hd-ui-theme.json: colors object required")
    for name, value in colors.items():
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("hd-ui-theme.json: color " + name + " must be packed RRGGBBAA")
    dlg = theme.get("dialog") or {}
    if dlg.get("radiusPx", 0) <= 0 or dlg.get("borderWidthPx", 0) <= 0:
        fail("hd-ui-theme.json: dialog.radiusPx/borderWidthPx must be > 0")
    shadow = theme.get("shadow") or {}
    halo = theme.get("halo") or {}
    if shadow.get("glowRadiusPx", 0) <= 0 or halo.get("glowRadiusPx", 0) <= 0:
        fail("hd-ui-theme.json: shadow/halo glowRadiusPx must be > 0")
    typography = theme.get("typography") or {}
    for key in ("titleFontSizeScale", "bodyFontSizeScale", "bodyLineHeight",
                "labelFontSizeScaleWide", "labelFontSizeScaleCompact",
                "bodyFontSizeScaleWide", "bodyFontSizeScaleCompact",
                "bodyFontWidthScaleWide", "bodyFontWidthScaleCompact",
                "bodyWrapMeasureScaleWide", "bodyWrapMeasureScaleCompact",
                "bodyProjectionLineHeightScaleWide", "bodyProjectionLineHeightScaleCompact"):
        if not isinstance(typography.get(key), (int, float)) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be > 0")
    for key in ("labelFontSizePx", "bodyFontSizePx", "titleFontWeight", "labelFontWeight", "bodyFontWeight"):
        if not isinstance(typography.get(key), int) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be a positive integer")
    f21_type = theme.get("f21Typography") or {}
    for key in ("protocolWidePx", "protocolCompactPx", "titleWidePx", "titleCompactPx",
                "dataWidePx", "dataCompactPx", "bodyWidePx", "bodyCompactPx",
                "inputWidePx", "inputCompactPx", "actionWidePx", "actionCompactPx"):
        if not isinstance(f21_type.get(key), int) or f21_type[key] <= 0:
            fail("hd-ui-theme.json: f21Typography." + key + " must be a positive integer")
    if (not isinstance(f21_type.get("bodyLineHeight"), (int, float))
            or f21_type["bodyLineHeight"] <= 1.0):
        fail("hd-ui-theme.json: f21Typography.bodyLineHeight must be > 1")
    f21_safe = theme.get("f21TextSafeArea") or {}
    for key in ("protocolInsetXWidePx", "protocolInsetXCompactPx",
                "protocolInsetYWidePx", "protocolInsetYCompactPx",
                "minimumHorizontalPaddingPx", "minimumVerticalPaddingPx"):
        if not isinstance(f21_safe.get(key), int) or f21_safe[key] < 4:
            fail("hd-ui-theme.json: f21TextSafeArea." + key + " must be an integer >= 4")


def validate_f33(f33):
    if f33.get("schema") != 1:
        fail("f33-abandon.json: schema must be 1")
    if not isinstance(f33.get("version"), str) or not f33["version"]:
        fail("f33-abandon.json: version string required")
    form = f33.get("form") or {}
    if (form.get("id") != "f33-abandon" or form.get("familyId") != 33
            or form.get("archetype") != "small-confirmation"
            or form.get("source") != "FormConfigs/f33-abandon.json"):
        fail("f33-abandon.json: generated form identity/provenance is invalid")
    icon = form.get("icon") or {}
    if icon != {"kind": "warning", "glyph": "!", "tone": "warning"}:
        fail("f33-abandon.json: generated warning icon metadata drifted")
    buttons = form.get("buttons")
    if not isinstance(buttons, list) or len(buttons) != 2:
        fail("f33-abandon.json: generated form requires two button descriptors")
    expected_buttons = (("cancel", "KEEP PLAYING", "safe", "cancel"),
                        ("confirm", "ABANDON GAME", "danger", "confirm"))
    for button, expected in zip(buttons, expected_buttons):
        if tuple(button.get(key) for key in ("id", "label", "tone", "action")) != expected:
            fail("f33-abandon.json: generated button metadata drifted")
        button_style = button.get("style") or {}
        for key in ("fill", "border", "text"):
            if not isinstance(button_style.get(key), str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", button_style[key]):
                fail("f33-abandon.json: generated button style " + key + " must be RRGGBBAA")
    copy = f33.get("copy") or {}
    for key in ("protocol", "title", "safeAction", "destructiveAction"):
        if not isinstance(copy.get(key), str) or not copy[key]:
            fail("f33-abandon.json: copy." + key + " string required")
    if (not isinstance(copy.get("message"), list) or len(copy["message"]) != 2
            or not all(isinstance(line, str) and line for line in copy["message"])):
        fail("f33-abandon.json: copy.message must contain exactly two non-empty lines")
    style = f33.get("style") or {}
    if not isinstance(style.get("cutCornerPx"), (int, float)) or style["cutCornerPx"] <= 0:
        fail("f33-abandon.json: style.cutCornerPx must be > 0")
    if (not isinstance(style.get("protocolTextInsetPx"), (int, float))
            or style["protocolTextInsetPx"] <= 0):
        fail("f33-abandon.json: style.protocolTextInsetPx must be > 0")
    if style["protocolTextInsetPx"] != style["cutCornerPx"] + 12:
        fail("f33-abandon.json: protocolTextInsetPx must be two mono cells after cutCornerPx")
    for key in ("panelFillTop", "panelFillBottom", "frame", "protocolText", "divider",
                "footerFill", "footerDot", "warning", "safeFill", "safeBorder",
                "destructiveFill", "destructiveText"):
        value = style.get(key)
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("f33-abandon.json: style." + key + " must be packed RRGGBBAA")
    layouts = f33.get("layouts")
    if not isinstance(layouts, dict) or "wide" not in layouts or "compact" not in layouts:
        fail("f33-abandon.json: explicit wide/compact layouts required")
    for name in ("wide", "compact"):
        l = layouts[name]
        if l.get("designWidth", 0) <= 0 or l.get("designHeight", 0) <= 0:
            fail("f33-abandon.json: " + name + " design canvas required")
        for part in ("window", "status", "warning", "title", "message", "footer", "yes", "no"):
            r = l.get(part)
            if not r or not all(isinstance(r[k], int) for k in ("x", "y", "width", "height")):
                fail("f33-abandon.json: " + name + "." + part + " must be an integer rect")
        button_rects = l.get("buttons") or {}
        if set(button_rects) != {"cancel", "confirm"}:
            fail("f33-abandon.json: " + name + ".buttons must resolve cancel/confirm slots")
        if button_rects["cancel"] != l["no"] or button_rects["confirm"] != l["yes"]:
            fail("f33-abandon.json: " + name + " compatibility button aliases drifted")
        for part in ("yes", "no"):
            if l[part]["width"] < MIN_ACTION_TARGET or l[part]["height"] < MIN_ACTION_TARGET:
                fail("f33-abandon.json: " + name + "." + part
                     + " below the " + str(MIN_ACTION_TARGET) + "x" + str(MIN_ACTION_TARGET)
                     + " action-target floor")

        def contained(inner, outer):
            return (inner["x"] >= outer["x"] and inner["y"] >= outer["y"]
                    and inner["x"] + inner["width"] <= outer["x"] + outer["width"]
                    and inner["y"] + inner["height"] <= outer["y"] + outer["height"])
        if not contained(l["window"], {"x": 0, "y": 0, "width": l["designWidth"], "height": l["designHeight"]}):
            fail("f33-abandon.json: " + name + ".window must fit the design canvas")
        for part in ("status", "warning", "title", "message", "footer", "yes", "no"):
            if not contained(l[part], l["window"]):
                fail("f33-abandon.json: " + name + "." + part + " must be inside the window")
        if (l["yes"]["x"] < l["no"]["x"] + l["no"]["width"] and l["no"]["x"] < l["yes"]["x"] + l["yes"]["width"]
                and l["yes"]["y"] < l["no"]["y"] + l["no"]["height"] and l["no"]["y"] < l["yes"]["y"] + l["yes"]["height"]):
            fail("f33-abandon.json: " + name + ".yes and .no must not overlap")
        if l["yes"]["x"] + l["yes"]["width"] != l["message"]["x"] + l["message"]["width"]:
            fail("f33-abandon.json: " + name + ".yes must end at the message content rail")
    m = f33.get("motion") or {}
    if m.get("durationMs", 0) <= 0 or m.get("durationMs", 0) > 1000:
        fail("f33-abandon.json: motion.durationMs must be in (0, 1000]")
    if not (0.0 < m.get("scaleFrom", 0.0) <= 1.0):
        fail("f33-abandon.json: motion.scaleFrom must be in (0, 1]")
    if m.get("captureModeDurationMs") != 0:
        fail("f33-abandon.json: captureModeDurationMs must be 0 (deterministic captures)")


IDENT_RE = _re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

# F21 (Phase 46.F21): part-list-driven family contracts. One generic validator
# + emitter serves every entry; the F33 bespoke path above stays untouched.
# (rel, namespace, rect-struct/layout prefix, JS global name)
F21_FAMILIES = [
    ("f21-site.json", "CalypsoF21SiteGen", "CalypsoF21Site", "CalypsoF21Site"),
    ("f21-transaction.json", "CalypsoF21TransactionGen", "CalypsoF21Transaction", "CalypsoF21Transaction"),
    ("f21-name.json", "CalypsoF21NameGen", "CalypsoF21Name", "CalypsoF21Name"),
    ("f21-defense.json", "CalypsoF21DefenseGen", "CalypsoF21Defense", "CalypsoF21Defense"),
    ("f21-destruction.json", "CalypsoF21DestructionGen", "CalypsoF21Destruction", "CalypsoF21Destruction"),
]

F21_COMMAND_CARD_CONTRACTS = {
    "f21-site.json", "f21-transaction.json", "f21-name.json",
    "f21-defense.json", "f21-destruction.json",
}

F21_ENGINE_TEXT_CALIBRATION_CONTRACTS = {
    "f21-site.json", "f21-transaction.json",
    "f21-defense.json", "f21-destruction.json",
}


def validate_f21(doc, rel):
    if doc.get("schema") != 1:
        fail(rel + ": schema must be 1")
    if not isinstance(doc.get("version"), str) or not VERSION_RE.match(doc.get("version", "")):
        fail(rel + ": version string required")
    if rel in F21_COMMAND_CARD_CONTRACTS:
        if doc.get("visualProfile") != "command-card-v1":
            fail(rel + ": visualProfile must be command-card-v1")
        copy = doc.get("copy")
        if not isinstance(copy, dict) or not copy:
            fail(rel + ": fixture copy object required")
        for key, value in copy.items():
            if not isinstance(value, str) or not value:
                fail(rel + ": copy." + key + " must be a non-empty string")
            if "{STRING}" in value or "{ALT}" in value:
                fail(rel + ": copy." + key + " contains legacy placeholder/control syntax")
    parts = doc.get("parts")
    if not isinstance(parts, list) or not parts:
        fail(rel + ": parts list required")
    if len(set(parts)) != len(parts):
        fail(rel + ": parts must be unique")
    for p in parts:
        if not isinstance(p, str) or not IDENT_RE.match(p):
            fail(rel + ": part name must be a C identifier: " + repr(p))
    if parts[0] != "window":
        fail(rel + ": first part must be the window root")
    actions = doc.get("actions")
    if not isinstance(actions, list):
        fail(rel + ": actions list required")
    for a in actions:
        if a not in parts:
            fail(rel + ": action " + repr(a) + " must be listed in parts")
    layouts = doc.get("layouts")
    if not isinstance(layouts, dict) or "wide" not in layouts or "compact" not in layouts:
        fail(rel + ": explicit wide/compact layouts required")
    for name in ("wide", "compact"):
        l = layouts[name]
        if l.get("designWidth", 0) <= 0 or l.get("designHeight", 0) <= 0:
            fail(rel + ": " + name + " design canvas required")
        for part in parts:
            r = l.get(part)
            if not r or not all(isinstance(r[k], int) for k in ("x", "y", "width", "height")):
                fail(rel + ": " + name + "." + part + " must be an integer rect")
        for a in actions:
            r = l[a]
            if r["width"] < MIN_ACTION_TARGET or r["height"] < MIN_ACTION_TARGET:
                fail(rel + ": " + name + "." + a
                     + " below the " + str(MIN_ACTION_TARGET) + "x" + str(MIN_ACTION_TARGET)
                     + " action-target floor")

        def contained(inner, outer):
            return (inner["x"] >= outer["x"] and inner["y"] >= outer["y"]
                    and inner["x"] + inner["width"] <= outer["x"] + outer["width"]
                    and inner["y"] + inner["height"] <= outer["y"] + outer["height"])
        if not contained(l["window"], {"x": 0, "y": 0, "width": l["designWidth"], "height": l["designHeight"]}):
            fail(rel + ": " + name + ".window must fit the design canvas")
        for part in parts:
            if part != "window" and not contained(l[part], l["window"]):
                fail(rel + ": " + name + "." + part + " must be inside the window")
        for i, a1 in enumerate(actions):
            for a2 in actions[i + 1:]:
                r1, r2 = l[a1], l[a2]
                if (r1["x"] < r2["x"] + r2["width"] and r2["x"] < r1["x"] + r1["width"]
                        and r1["y"] < r2["y"] + r2["height"] and r2["y"] < r1["y"] + r1["height"]):
                    fail(rel + ": " + name + " actions " + a1 + " and " + a2 + " must not overlap")
    m = doc.get("motion") or {}
    if m.get("durationMs", 0) <= 0 or m.get("durationMs", 0) > 1000:
        fail(rel + ": motion.durationMs must be in (0, 1000]")
    if not (0.0 < m.get("scaleFrom", 0.0) <= 1.0):
        fail(rel + ": motion.scaleFrom must be in (0, 1]")
    if m.get("captureModeDurationMs") != 0:
        fail(rel + ": captureModeDurationMs must be 0 (deterministic captures)")

    if rel in F21_COMMAND_CARD_CONTRACTS:
        spacing = doc.get("spacingRules")
        if not isinstance(spacing, list) or not spacing:
            fail(rel + ": spacingRules must be a non-empty list")
        seen_ids = set()
        for rule in spacing:
            if not isinstance(rule, dict):
                fail(rel + ": each spacing rule must be an object")
            rid = rule.get("id")
            if not isinstance(rid, str) or not rid or rid in seen_ids:
                fail(rel + ": spacing rule ids must be non-empty and unique")
            seen_ids.add(rid)
            kind = rule.get("kind")
            for layout_name in ("wide", "compact"):
                minimum = rule.get(layout_name)
                if not isinstance(minimum, int) or minimum <= 0:
                    fail(rel + ": spacing " + rid + "." + layout_name + " must be a positive integer")
            if kind == "gap":
                first, second, axis = rule.get("first"), rule.get("second"), rule.get("axis")
                if first not in parts or second not in parts or axis not in ("horizontal", "vertical"):
                    fail(rel + ": gap " + rid + " must reference two parts and a supported axis")
                for layout_name in ("wide", "compact"):
                    first_rect, second_rect = layouts[layout_name][first], layouts[layout_name][second]
                    gap = (second_rect["x"] - first_rect["x"] - first_rect["width"]
                           if axis == "horizontal"
                           else second_rect["y"] - first_rect["y"] - first_rect["height"])
                    if gap < rule[layout_name]:
                        fail(rel + ": " + layout_name + " gap " + rid + " is " + str(gap)
                             + ", expected >= " + str(rule[layout_name]))
            elif kind == "inset":
                container, child, edges = rule.get("container"), rule.get("child"), rule.get("edges")
                if container not in parts or child not in parts:
                    fail(rel + ": inset " + rid + " must reference container and child parts")
                if (not isinstance(edges, list) or not edges
                        or any(edge not in ("left", "right", "top", "bottom") for edge in edges)):
                    fail(rel + ": inset " + rid + " has unsupported edges")
                for layout_name in ("wide", "compact"):
                    outer, inner = layouts[layout_name][container], layouts[layout_name][child]
                    insets = {
                        "left": inner["x"] - outer["x"],
                        "right": outer["x"] + outer["width"] - inner["x"] - inner["width"],
                        "top": inner["y"] - outer["y"],
                        "bottom": outer["y"] + outer["height"] - inner["y"] - inner["height"],
                    }
                    for edge in edges:
                        if insets[edge] < rule[layout_name]:
                            fail(rel + ": " + layout_name + " inset " + rid + "." + edge
                                 + " is " + str(insets[edge]) + ", expected >= " + str(rule[layout_name]))
            else:
                fail(rel + ": spacing " + rid + " kind must be gap or inset")

    calibration = doc.get("engineTextScale")
    if rel in F21_ENGINE_TEXT_CALIBRATION_CONTRACTS:
        if not isinstance(calibration, dict):
            fail(rel + ": engineTextScale object required")
        for role in ("title", "data", "body", "input", "action"):
            scale = calibration.get(role)
            if not isinstance(scale, (int, float)) or not (0.0 < scale <= 1.0):
                fail(rel + ": engineTextScale." + role + " must be in (0, 1]")


def rgba_call(value):
    # Emit the packed 0xRRGGBBAA word directly: the generated header stays
    # dependency-free (no CalypsoHdUiModel.h include needed).
    return "0x%08Xu" % int(value, 16)


def emit_theme_h(theme):
    colors = theme["colors"]
    out = [HEADER_BANNER,
           "// Canonical source: src/Calypso/Contracts/hd-ui-theme.json",
           "#pragma once",
           "#include <cstdint>",
           "#include <cstring>",
           "namespace OpenXcom { namespace Calypso { namespace CalypsoHdThemeGen {",
           'inline constexpr const char* kContractVersion = "' + theme["version"] + '";',
           "",
           "// Semantic palette (0xRRGGBBAA).",
           ]
    for name in sorted(colors.keys()):
        const = "k" + name[0].upper() + name[1:]
        out.append("inline constexpr std::uint32_t " + const + " = " + rgba_call(colors[name]) + ";")
    out.append("")
    out.append("// Style parameters (design px).")
    out.append("inline constexpr float kDialogRadiusPx = %.6ff;" % float(theme["dialog"]["radiusPx"]))
    out.append("inline constexpr float kButtonRadiusPx = %.6ff;" % float(theme["button"]["radiusPx"]))
    out.append("inline constexpr float kBorderWidthPx = %.6ff;" % float(theme["dialog"]["borderWidthPx"]))
    out.append("inline constexpr float kTitleTrackingEm = %.6ff;" % float(theme["tracking"]["titleEm"]))
    out.append("inline constexpr float kLabelTrackingEm = %.6ff;" % float(theme["tracking"]["labelEm"]))
    out.append("inline constexpr float kShadowGlowRadiusPx = %.6ff;" % float(theme["shadow"]["glowRadiusPx"]))
    out.append("inline constexpr float kHaloGlowRadiusPx = %.6ff;" % float(theme["halo"]["glowRadiusPx"]))
    out.append("inline constexpr float kTitleFontSizeScale = %.6ff;" % float(theme["typography"]["titleFontSizeScale"]))
    out.append("inline constexpr float kBodyFontSizeScale = %.6ff;" % float(theme["typography"]["bodyFontSizeScale"]))
    out.append("inline constexpr int kLabelFontSizePx = %d;" % int(theme["typography"]["labelFontSizePx"]))
    out.append("inline constexpr float kLabelFontSizeScaleWide = %.6ff;" % float(theme["typography"]["labelFontSizeScaleWide"]))
    out.append("inline constexpr float kLabelFontSizeScaleCompact = %.6ff;" % float(theme["typography"]["labelFontSizeScaleCompact"]))
    out.append("inline constexpr int kBodyFontSizePx = %d;" % int(theme["typography"]["bodyFontSizePx"]))
    out.append("inline constexpr float kBodyFontSizeScaleWide = %.6ff;" % float(theme["typography"]["bodyFontSizeScaleWide"]))
    out.append("inline constexpr float kBodyFontSizeScaleCompact = %.6ff;" % float(theme["typography"]["bodyFontSizeScaleCompact"]))
    out.append("inline constexpr float kBodyFontWidthScaleWide = %.6ff;" % float(theme["typography"]["bodyFontWidthScaleWide"]))
    out.append("inline constexpr float kBodyFontWidthScaleCompact = %.6ff;" % float(theme["typography"]["bodyFontWidthScaleCompact"]))
    out.append("inline constexpr float kBodyWrapMeasureScaleWide = %.6ff;" % float(theme["typography"]["bodyWrapMeasureScaleWide"]))
    out.append("inline constexpr float kBodyWrapMeasureScaleCompact = %.6ff;" % float(theme["typography"]["bodyWrapMeasureScaleCompact"]))
    out.append("inline constexpr float kBodyProjectionLineHeightScaleWide = %.6ff;" % float(theme["typography"]["bodyProjectionLineHeightScaleWide"]))
    out.append("inline constexpr float kBodyProjectionLineHeightScaleCompact = %.6ff;" % float(theme["typography"]["bodyProjectionLineHeightScaleCompact"]))
    out.append("inline constexpr float kBodyLineHeight = %.6ff;" % float(theme["typography"]["bodyLineHeight"]))
    out.append("inline constexpr int kTitleFontWeight = %d;" % int(theme["typography"]["titleFontWeight"]))
    out.append("inline constexpr int kLabelFontWeight = %d;" % int(theme["typography"]["labelFontWeight"]))
    out.append("inline constexpr int kBodyFontWeight = %d;" % int(theme["typography"]["bodyFontWeight"]))
    out.append("")
    out.append("// F21 command-card typography and hard text safe area (design px).")
    for key, value in theme["f21Typography"].items():
        name = "kF21" + key[0].upper() + key[1:]
        if key == "bodyLineHeight":
            out.append("inline constexpr float " + name + " = %.6ff;" % float(value))
        else:
            out.append("inline constexpr int " + name + " = %d;" % int(value))
    for key, value in theme["f21TextSafeArea"].items():
        out.append("inline constexpr int kF21" + key[0].upper() + key[1:] + " = %d;" % int(value))
    out.append("")
    out.append("// Semantic token key strings for the interaction-state mapping")
    out.append("// (CalypsoHdInteractionState.h) -- values above, keys here.")
    names = sorted(colors.keys())
    for name in names:
        token = "token.color." + name
        const = "kToken" + name[0].upper() + name[1:]
        out.append('inline constexpr const char* ' + const + ' = "' + token + '";')
    out.append("")
    out.append("/// Resolve a semantic token key to its packed RGBA value (0 for")
    out.append("/// unknown keys). Generated table; one source of truth.")
    out.append("inline std::uint32_t calypsoHdThemeColorForToken(const char* token)")
    out.append("{")
    out.append(TAB + "struct Entry { const char* key; std::uint32_t value; };")
    out.append(TAB + "static constexpr Entry kEntries[] = {")
    for name in names:
        const = "k" + name[0].upper() + name[1:]
        tconst = "kToken" + name[0].upper() + name[1:]
        out.append(TAB + TAB + "{ " + tconst + ", " + const + " },")
    out.append(TAB + "};")
    out.append(TAB + "for (const Entry& e : kEntries)")
    out.append(TAB + TAB + "if (std::strcmp(token, e.key) == 0) return e.value;")
    out.append(TAB + "return 0;")
    out.append("}")
    out.append("} } }")
    return NL.join(out) + NL


def f33_rect(l, part):
    r = l[part]
    return "{ " + str(r["x"]) + ", " + str(r["y"]) + ", " + str(r["width"]) + ", " + str(r["height"]) + " }"


