def ensure_generated_dir():
    os.makedirs(GENERATED_DIR, exist_ok=True)


def main(argv):
    parser = argparse.ArgumentParser(description="generate HD UI contracts")
    parser.add_argument("--check", action="store_true",
                        help="validate + compare without writing; exit 1 on stale output")
    parser.add_argument("--web-output", default=None,
                        help="directory (relative to CWD) for the generated DOM modules")
    parser.add_argument("--registry", default=REGISTRY_PATH,
                        help="canonical contract registry (default: " + REGISTRY_REL + ")")
    args = parser.parse_args(argv)

    registry_path = args.registry if os.path.isabs(args.registry) else os.path.join(os.getcwd(), args.registry)
    entries = validate_registry(load_registry(registry_path))
    docs = []
    for entry in entries:
        rel = entry["contract"]
        doc = load_json(rel)
        if entry["emitter"] == "theme":
            validate_theme(doc)
        elif entry["emitter"] == "legacy-abandon":
            validate_f33(doc)
        elif entry["emitter"] == "screen":
            validate_screen(doc, rel)
        else:
            validate_family(doc, rel, entry["validationProfile"],
                            entry.get("engineTextCalibration", False))
        docs.append((entry, doc))
    versions = [(entry["contract"], doc["version"]) for entry, doc in docs]
    for rel, ver in versions[1:]:
        if ver != versions[0][1]:
            fail("contract versions diverge: " + versions[0][0] + " " + versions[0][1]
                 + " vs " + rel + " " + ver)

    # Directory creation happens ONLY on the write path -- --check performs
    # no writes at all (normative rule, generator docstring).
    outputs = []
    web = None
    if args.web_output:
        web = args.web_output if os.path.isabs(args.web_output) else os.path.join(os.getcwd(), args.web_output)
    for entry, doc in docs:
        rel = entry["contract"]
        native = entry["native"]
        if entry["emitter"] == "theme":
            native_text = emit_theme_h(doc)
        elif entry["emitter"] == "legacy-abandon":
            native_text = emit_f33_h(doc)
        elif entry["emitter"] == "screen":
            native_text = emit_screen_h(
                doc, rel, native["namespace"], native["prefix"])
        elif entry["validationProfile"] in {"small-confirmation", "contact-decision"}:
            native_text = emit_small_confirmation_h(
                doc, rel, native["namespace"], native["prefix"])
        else:
            native_text = emit_family_h(
                doc, rel, native["namespace"], native["prefix"], entry["validationProfile"])
        outputs.append((os.path.join(GENERATED_DIR, native["output"]), native_text))
        if web is not None:
            browser = entry["browser"]
            outputs.append((os.path.join(web, browser["output"]),
                            emit_js(rel, doc, browser["global"])))

    if args.check:
        changed = []
        for path, text in outputs:
            current = None
            if os.path.isfile(path):
                with open(path, "r", encoding="utf-8") as f:
                    current = f.read()
            if current != text:
                changed.append(path)
        if changed:
            for path in changed:
                print("generate-hd-ui-contracts: STALE: " + path)
            print("generate-hd-ui-contracts: run without --check to regenerate; never hand-edit generated consumers")
            return 1
        print("generate-hd-ui-contracts: all " + str(len(outputs)) + " consumers are current")
        return 0

    ensure_generated_dir()
    if web is not None:
        os.makedirs(web, exist_ok=True)
    for path, text in outputs:
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)
    print("generate-hd-ui-contracts: wrote " + str(len(outputs)) + " generated consumers")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
