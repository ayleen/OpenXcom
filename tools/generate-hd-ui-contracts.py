def validate_theme(theme):
    if theme.get("schema") != 1:
        fail("hd-ui-theme.json: schema must be 1")
    if not isinstance(theme.get("version"), str) or not VERSION_RE.match(theme.get("version", "")):
        fail("hd-ui-theme.json: version string required (^[A-Za-z0-9._-]+$)")
    colors = theme.get("colors")
    if not isinstance(colors, dict) or not colors:
        fail("hd-ui-theme.json: colors object required")
    for name, value in colors.items():
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("hd-ui-theme.json: color " + name + " must be packed RRGGBBAA")
    dlg = theme.get("dialog") or {}
    if dlg.get("radiusPx", 0) <= 0 or dlg.get("borderWidthPx", 0) <= 0:
        fail("hd-ui-theme.json: dialog.radiusPx/borderWidthPx must be > 0")
    shadow = theme.get("shadow") or {}
    halo = theme.get("halo") or {}
    if shadow.get("glowRadiusPx", 0) <= 0 or halo.get("glowRadiusPx", 0) <= 0:
        fail("hd-ui-theme.json: shadow/halo glowRadiusPx must be > 0")
    typography = theme.get("typography") or {}
    for key in ("titleFontSizeScale", "bodyFontSizeScale", "bodyLineHeight",
                "labelFontSizeScaleWide", "labelFontSizeScaleCompact",
                "bodyFontSizeScaleWide", "bodyFontSizeScaleCompact",
                "bodyFontWidthScaleWide", "bodyFontWidthScaleCompact",
                "bodyWrapMeasureScaleWide", "bodyWrapMeasureScaleCompact",
                "bodyProjectionLineHeightScaleWide", "bodyProjectionLineHeightScaleCompact"):
        if not isinstance(typography.get(key), (int, float)) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be > 0")
    for key in ("labelFontSizePx", "bodyFontSizePx", "titleFontWeight", "labelFontWeight", "bodyFontWeight"):
        if not isinstance(typography.get(key), int) or typography[key] <= 0:
            fail("hd-ui-theme.json: typography." + key + " must be a positive integer")
    f21_type = theme.get("f21Typography") or {}
    for key in ("protocolWidePx", "protocolCompactPx", "titleWidePx", "titleCompactPx",
                "dataWidePx", "dataCompactPx", "bodyWidePx", "bodyCompactPx",
                "inputWidePx", "inputCompactPx", "actionWidePx", "actionCompactPx"):
        if not isinstance(f21_type.get(key), int) or f21_type[key] <= 0:
            fail("hd-ui-theme.json: f21Typography." + key + " must be a positive integer")
    if (not isinstance(f21_type.get("bodyLineHeight"), (int, float))
            or f21_type["bodyLineHeight"] <= 1.0):
        fail("hd-ui-theme.json: f21Typography.bodyLineHeight must be > 1")
    f21_safe = theme.get("f21TextSafeArea") or {}
    for key in ("protocolInsetXWidePx", "protocolInsetXCompactPx",
                "protocolInsetYWidePx", "protocolInsetYCompactPx",
                "minimumHorizontalPaddingPx", "minimumVerticalPaddingPx"):
        if not isinstance(f21_safe.get(key), int) or f21_safe[key] < 4:
            fail("hd-ui-theme.json: f21TextSafeArea." + key + " must be an integer >= 4")
    command_action = theme.get("commandAction") or {}
    for key in COMMAND_ACTION_COLOR_KEYS:
        value = command_action.get(key)
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("hd-ui-theme.json: commandAction." + key + " must be packed RRGGBBAA")
    for key in COMMAND_ACTION_GLOW_RADIUS_KEYS:
        if not isinstance(command_action.get(key), (int, float)) or command_action[key] <= 0:
            fail("hd-ui-theme.json: commandAction." + key + " must be > 0")
    if not isinstance(command_action.get("radiusPx"), (int, float)) or command_action["radiusPx"] <= 0:
        fail("hd-ui-theme.json: commandAction.radiusPx must be > 0")
    if command_action.get("hoverGlowRadiusPx", 0) <= command_action.get("restGlowRadiusPx", 1):
        fail("hd-ui-theme.json: commandAction.hoverGlowRadiusPx must read stronger than rest")
    if command_action.get("pressedGlowRadiusPx", 1) >= command_action.get("restGlowRadiusPx", 0):
        fail("hd-ui-theme.json: commandAction.pressedGlowRadiusPx must read tighter than rest")


def validate_f33(f33):
    if f33.get("schema") != 1:
        fail("f33-abandon.json: schema must be 1")
    if not isinstance(f33.get("version"), str) or not f33["version"]:
        fail("f33-abandon.json: version string required")
    form = f33.get("form") or {}
    if (form.get("id") != "f33-abandon" or form.get("familyId") != 33
            or form.get("archetype") != "small-confirmation"
            or form.get("source") != "FormConfigs/f33-abandon.json"):
        fail("f33-abandon.json: generated form identity/provenance is invalid")
    icon = form.get("icon") or {}
    if icon != {"kind": "warning", "glyph": "!", "tone": "warning"}:
        fail("f33-abandon.json: generated warning icon metadata drifted")
    buttons = form.get("buttons")
    if not isinstance(buttons, list) or len(buttons) != 2:
        fail("f33-abandon.json: generated form requires two button descriptors")
    expected_buttons = (("cancel", "KEEP PLAYING", "safe", "cancel"),
                        ("confirm", "ABANDON GAME", "danger", "confirm"))
    for button, expected in zip(buttons, expected_buttons):
        if tuple(button.get(key) for key in ("id", "label", "tone", "action")) != expected:
            fail("f33-abandon.json: generated button metadata drifted")
        button_style = button.get("style") or {}
        for key in ("fill", "border", "text"):
            if not isinstance(button_style.get(key), str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", button_style[key]):
                fail("f33-abandon.json: generated button style " + key + " must be RRGGBBAA")
    copy = f33.get("copy") or {}
    for key in ("protocol", "title", "safeAction", "destructiveAction"):
        if not isinstance(copy.get(key), str) or not copy[key]:
            fail("f33-abandon.json: copy." + key + " string required")
    if (not isinstance(copy.get("message"), list) or len(copy["message"]) != 2
            or not all(isinstance(line, str) and line for line in copy["message"])):
        fail("f33-abandon.json: copy.message must contain exactly two non-empty lines")
    style = f33.get("style") or {}
    if not isinstance(style.get("cutCornerPx"), (int, float)) or style["cutCornerPx"] <= 0:
        fail("f33-abandon.json: style.cutCornerPx must be > 0")
    if (not isinstance(style.get("protocolTextInsetPx"), (int, float))
            or style["protocolTextInsetPx"] <= 0):
        fail("f33-abandon.json: style.protocolTextInsetPx must be > 0")
    if style["protocolTextInsetPx"] != style["cutCornerPx"] + 12:
        fail("f33-abandon.json: protocolTextInsetPx must be two mono cells after cutCornerPx")
    for key in ("panelFillTop", "panelFillBottom", "frame", "protocolText", "divider",
                "footerFill", "footerDot", "warning", "safeFill", "safeBorder",
                "destructiveFill", "destructiveText"):
        value = style.get(key)
        if not isinstance(value, str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
            fail("f33-abandon.json: style." + key + " must be packed RRGGBBAA")
    layouts = f33.get("layouts")
    if not isinstance(layouts, dict) or "wide" not in layouts or "compact" not in layouts:
        fail("f33-abandon.json: explicit wide/compact layouts required")
    for name in ("wide", "compact"):
        l = layouts[name]
        if l.get("designWidth", 0) <= 0 or l.get("designHeight", 0) <= 0:
            fail("f33-abandon.json: " + name + " design canvas required")
        for part in ("window", "status", "warning", "title", "message", "footer", "yes", "no"):
            r = l.get(part)
            if not r or not all(isinstance(r[k], int) for k in ("x", "y", "width", "height")):
                fail("f33-abandon.json: " + name + "." + part + " must be an integer rect")
        button_rects = l.get("buttons") or {}
        if set(button_rects) != {"cancel", "confirm"}:
            fail("f33-abandon.json: " + name + ".buttons must resolve cancel/confirm slots")
        if button_rects["cancel"] != l["no"] or button_rects["confirm"] != l["yes"]:
            fail("f33-abandon.json: " + name + " compatibility button aliases drifted")
        for part in ("yes", "no"):
            if l[part]["width"] < MIN_ACTION_TARGET or l[part]["height"] < MIN_ACTION_TARGET:
                fail("f33-abandon.json: " + name + "." + part
                     + " below the " + str(MIN_ACTION_TARGET) + "x" + str(MIN_ACTION_TARGET)
                     + " action-target floor")

        def contained(inner, outer):
            return (inner["x"] >= outer["x"] and inner["y"] >= outer["y"]
                    and inner["x"] + inner["width"] <= outer["x"] + outer["width"]
                    and inner["y"] + inner["height"] <= outer["y"] + outer["height"])
        if not contained(l["window"], {"x": 0, "y": 0, "width": l["designWidth"], "height": l["designHeight"]}):
            fail("f33-abandon.json: " + name + ".window must fit the design canvas")
        for part in ("status", "warning", "title", "message", "footer", "yes", "no"):
            if not contained(l[part], l["window"]):
                fail("f33-abandon.json: " + name + "." + part + " must be inside the window")
        if (l["yes"]["x"] < l["no"]["x"] + l["no"]["width"] and l["no"]["x"] < l["yes"]["x"] + l["yes"]["width"]
                and l["yes"]["y"] < l["no"]["y"] + l["no"]["height"] and l["no"]["y"] < l["yes"]["y"] + l["yes"]["height"]):
            fail("f33-abandon.json: " + name + ".yes and .no must not overlap")
        if l["yes"]["x"] + l["yes"]["width"] != l["message"]["x"] + l["message"]["width"]:
            fail("f33-abandon.json: " + name + ".yes must end at the message content rail")
    m = f33.get("motion") or {}
    if m.get("durationMs", 0) <= 0 or m.get("durationMs", 0) > 1000:
        fail("f33-abandon.json: motion.durationMs must be in (0, 1000]")
    if not (0.0 < m.get("scaleFrom", 0.0) <= 1.0):
        fail("f33-abandon.json: motion.scaleFrom must be in (0, 1]")
    if m.get("captureModeDurationMs") != 0:
        fail("f33-abandon.json: captureModeDurationMs must be 0 (deterministic captures)")


IDENT_RE = _re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SLUG_RE = _re.compile(r"^[a-z0-9][a-z0-9-]*$")


def load_registry(path):
    if not os.path.isfile(path):
        fail("contract registry missing: " + path)
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def validate_registry(registry):
    if registry.get("schema") != 1:
        fail("hd-ui-contracts.json: schema must be 1")
    entries = registry.get("entries")
    if not isinstance(entries, list) or not entries:
        fail("hd-ui-contracts.json: non-empty entries array required")
    seen = {"id": set(), "contract": set(), "native output": set(), "browser output": set()}
    allowed_emitters = {"theme", "legacy-abandon", "family", "screen"}
    allowed_profiles = {"theme", "legacy-abandon", "family", "command-card",
                        "small-confirmation", "contact-decision", "content-block", "screen"}
    for index, entry in enumerate(entries):
        where = "hd-ui-contracts.json: entries[" + str(index) + "]"
        if not isinstance(entry, dict):
            fail(where + " must be an object")
        contract_id = entry.get("id")
        contract = entry.get("contract")
        emitter = entry.get("emitter")
        profile = entry.get("validationProfile")
        native = entry.get("native") or {}
        browser = entry.get("browser") or {}
        if not isinstance(contract_id, str) or not SLUG_RE.match(contract_id):
            fail(where + ".id must be a lower-kebab identifier")
        if not isinstance(contract, str) or not re.fullmatch(r"[a-z0-9-]+\.json", contract):
            fail(where + ".contract must be a Contracts/*.json basename")
        if emitter not in allowed_emitters or profile not in allowed_profiles:
            fail(where + " has an unsupported emitter or validationProfile")
        if ((emitter == "theme") != (profile == "theme")
                or (emitter == "legacy-abandon") != (profile == "legacy-abandon")):
            fail(where + " emitter and validationProfile are incompatible")
        if (emitter == "screen") != (profile == "screen"):
            fail(where + " screen emitter requires the screen validationProfile")
        for key in ("namespace", "prefix"):
            if not isinstance(native.get(key), str) or not IDENT_RE.match(native[key]):
                fail(where + ".native." + key + " must be a C++ identifier")
        if (not isinstance(native.get("output"), str)
                or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*\.generated\.h", native["output"])):
            fail(where + ".native.output must be a generated header basename")
        if not isinstance(browser.get("global"), str) or not IDENT_RE.match(browser["global"]):
            fail(where + ".browser.global must be a JavaScript identifier")
        if (not isinstance(browser.get("output"), str)
                or not re.fullmatch(r"[a-z0-9-]+\.js", browser["output"])):
            fail(where + ".browser.output must be a generated JavaScript basename")
        if not isinstance(entry.get("rendererOwnership"), str) or not entry["rendererOwnership"]:
            fail(where + ".rendererOwnership must be a non-empty string")
        scenarios = entry.get("harnessScenarioIds")
        if (not isinstance(scenarios, list)
                or any(not isinstance(value, int) or isinstance(value, bool) or value <= 0
                       for value in scenarios)):
            fail(where + ".harnessScenarioIds must contain positive integer ids")
        for label, value in (("id", contract_id), ("contract", contract),
                             ("native output", native["output"]),
                             ("browser output", browser["output"])):
            if value in seen[label]:
                fail(where + " duplicates " + label + " " + value)
            seen[label].add(value)
        if "engineTextCalibration" in entry and not isinstance(entry["engineTextCalibration"], bool):
            fail(where + ".engineTextCalibration must be boolean")
    return entries


def validate_family(doc, rel, profile, engine_text_calibration=False):
    if doc.get("schema") != 1:
        fail(rel + ": schema must be 1")
    if not isinstance(doc.get("version"), str) or not VERSION_RE.match(doc.get("version", "")):
        fail(rel + ": version string required")
    if profile in {"small-confirmation", "contact-decision"}:
        form = doc.get("form") or {}
        if form.get("archetype") != profile or not form.get("id"):
            fail(rel + ": " + profile + " form identity required")
        if doc.get("style") is None or doc.get("layouts") is None:
            fail(rel + ": " + profile + " form must carry style/layouts")
        presentation = doc.get("presentation") or {}
        density = presentation.get("density")
        numerator = presentation.get("scaleNumerator")
        denominator = presentation.get("scaleDenominator")
        if density not in ("standard", "brief-acknowledgement"):
            fail(rel + ": generated density profile is invalid")
        if (not isinstance(numerator, int) or not isinstance(denominator, int)
                or numerator <= 0 or denominator <= 0):
            fail(rel + ": generated density scale must be a positive integer ratio")
        if density == "standard" and (numerator, denominator) != (1, 1):
            fail(rel + ": standard density must use scale 1/1")
        if density == "brief-acknowledgement" and (numerator, denominator) != (2, 3):
            fail(rel + ": brief acknowledgement density must use scale 2/3")
        for layout_name in ("wide", "compact"):
            layout = doc["layouts"].get(layout_name) or {}
            buttons = layout.get("buttons") or {}
            if set(buttons) != {button["id"] for button in form.get("buttons", [])}:
                fail(rel + ": " + layout_name + " generated button geometry is incomplete")
            visible_action_floor = (MIN_ACTION_TARGET * numerator + denominator // 2) // denominator
            for button_id, rect in buttons.items():
                if (rect.get("width", 0) < visible_action_floor
                        or rect.get("height", 0) < visible_action_floor):
                    fail(rel + ": " + layout_name + ".buttons." + button_id
                         + " below the density-scaled " + str(visible_action_floor) + "x"
                         + str(visible_action_floor) + " visible-action floor")
            if form.get("buttons"):
                rightmost = buttons[form["buttons"][-1]["id"]]
                message = layout.get("message") or {}
                if (rightmost["x"] + rightmost["width"]
                        != message.get("x", 0) + message.get("width", 0)):
                    fail(rel + ": " + layout_name + " rightmost action left the text rail")
        return
    if profile == "command-card":
        if doc.get("visualProfile") != "command-card-v1":
            fail(rel + ": visualProfile must be command-card-v1")
        copy = doc.get("copy")
        if not isinstance(copy, dict) or not copy:
            fail(rel + ": fixture copy object required")
        for key, value in copy.items():
            if not isinstance(value, str) or not value:
                fail(rel + ": copy." + key + " must be a non-empty string")
            if "{STRING}" in value or "{ALT}" in value:
                fail(rel + ": copy." + key + " contains legacy placeholder/control syntax")
    if profile == "content-block":
        if doc.get("visualProfile") != "content-block-v1":
            fail(rel + ": visualProfile must be content-block-v1")
        block = doc.get("block") or {}
        if (block.get("archetype") != "content-block"
                or block.get("contentKind") not in ("text", "table")):
            fail(rel + ": generated content-block identity is invalid")
        if doc.get("presentation") != {"fitFailure": "exception", "legacyFallback": False}:
            fail(rel + ": content block must fail fast without legacy fallback")
        style = doc.get("style") or {}
        for key in ("panelFillTop", "panelFillBottom", "frame", "divider", "text"):
            if not isinstance(style.get(key), str) or not re.fullmatch(r"[0-9A-Fa-f]{8}", style[key]):
                fail(rel + ": style." + key + " must be packed 8-digit RGBA")
        for key in ("cutCornerPx", "borderWidthPx"):
            if not isinstance(style.get(key), int) or isinstance(style.get(key), bool) or style[key] <= 0:
                fail(rel + ": style." + key + " must be a positive integer")
        if any(key in (doc.get("copy") or {}) for key in
               ("title", "status", "protocol", "footer", "buttons")):
            fail(rel + ": content block emitted forbidden form chrome")
        content = doc.get("content") or {}
        if content.get("kind") != block.get("contentKind"):
            fail(rel + ": content kind must match generated block identity")
        if content.get("kind") == "table":
            columns = content.get("columns")
            rows = content.get("rows")
            if (not isinstance(columns, int) or columns < 2
                    or not isinstance(rows, list) or not rows):
                fail(rel + ": table content requires rows and at least two columns")
            if any(not isinstance(row, list) or len(row) != columns
                   or any(not isinstance(cell, str) or not cell for cell in row)
                   for row in rows):
                fail(rel + ": table rows must contain equal non-empty string cells")
            cell_parts = ["cellR" + str(row + 1) + "C" + str(column + 1)
                          for row in range(len(rows)) for column in range(columns)]
            expected_parts = (["window"]
                              + ["columnDivider" + str(index)
                                 for index in range(1, columns)]
                              + ["rowDivider" + str(index)
                                 for index in range(1, len(rows))]
                              + cell_parts)
            if doc.get("parts") != expected_parts:
                fail(rel + ": table parts do not match generated rows and columns")
            expected_copy = {part: rows[row][column]
                             for row in range(len(rows))
                             for column, part in enumerate(
                                 cell_parts[row * columns:(row + 1) * columns])}
            if doc.get("copy") != expected_copy:
                fail(rel + ": table copy does not match generated cells")
        else:
            value = content.get("value")
            if not isinstance(value, str) or not value:
                fail(rel + ": plain-text content requires a non-empty value")
            if doc.get("parts") != ["window", "text"] or doc.get("copy") != {"text": value}:
                fail(rel + ": plain-text parts/copy do not match generated content")
        metrics = doc.get("metrics") or {}
        if set(metrics) != {"wide", "compact"}:
            fail(rel + ": content block metrics must cover Wide and Compact")
        for layout_name in ("wide", "compact"):
            layout_metrics = metrics[layout_name]
            if not isinstance(layout_metrics, dict):
                fail(rel + ": " + layout_name + " metrics must be an object")
            guarded = layout_metrics.get("guardedLineHeight")
            if not isinstance(guarded, int) or guarded <= 0:
                fail(rel + ": " + layout_name + " guardedLineHeight must be positive")
            if content.get("kind") == "table":
                counts = layout_metrics.get("lineCounts")
                if (not isinstance(counts, dict) or set(counts) != set(cell_parts)
                        or any(not isinstance(count, int) or count <= 0
                               for count in counts.values())):
                    fail(rel + ": " + layout_name + " lineCounts must cover every cell")
                column_widths = layout_metrics.get("columnWidths")
                if (not isinstance(column_widths, list) or len(column_widths) != columns
                        or any(not isinstance(width, int) or width <= 0
                               for width in column_widths)):
                    fail(rel + ": " + layout_name + " columnWidths must cover every column")
                alignment = layout_metrics.get("alignment")
                if (not isinstance(alignment, dict) or set(alignment) != set(cell_parts)
                        or any(value != "top-left" for value in alignment.values())):
                    fail(rel + ": " + layout_name + " every cell must be top-left aligned")
            else:
                count = layout_metrics.get("lineCount")
                if not isinstance(count, int) or count <= 0:
                    fail(rel + ": " + layout_name + " lineCount must be positive")
                if layout_metrics.get("alignment") != "top-left":
                    fail(rel + ": " + layout_name + " text must be top-left aligned")
            for metric_name in ("maxBlockWidth", "textUnitWidth"):
                value = layout_metrics.get(metric_name)
                if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
                    fail(rel + ": " + layout_name + " " + metric_name + " must be positive")
    parts = doc.get("parts")
    if not isinstance(parts, list) or not parts:
        fail(rel + ": parts list required")
    if len(set(parts)) != len(parts):
        fail(rel + ": parts must be unique")
    for p in parts:
        if not isinstance(p, str) or not IDENT_RE.match(p):
            fail(rel + ": part name must be a C identifier: " + repr(p))
    if parts[0] != "window":
        fail(rel + ": first part must be the window root")
    actions = doc.get("actions")
    if not isinstance(actions, list):
        fail(rel + ": actions list required")
    for a in actions:
        if a not in parts:
            fail(rel + ": action " + repr(a) + " must be listed in parts")
    layouts = doc.get("layouts")
    if not isinstance(layouts, dict) or "wide" not in layouts or "compact" not in layouts:
        fail(rel + ": explicit wide/compact layouts required")
    for name in ("wide", "compact"):
        l = layouts[name]
        if l.get("designWidth", 0) <= 0 or l.get("designHeight", 0) <= 0:
            fail(rel + ": " + name + " design canvas required")
        for part in parts:
            r = l.get(part)
            if not r or not all(isinstance(r[k], int) for k in ("x", "y", "width", "height")):
                fail(rel + ": " + name + "." + part + " must be an integer rect")
        for a in actions:
            r = l[a]
            if r["width"] < MIN_ACTION_TARGET or r["height"] < MIN_ACTION_TARGET:
                fail(rel + ": " + name + "." + a
                     + " below the " + str(MIN_ACTION_TARGET) + "x" + str(MIN_ACTION_TARGET)
                     + " action-target floor")

        def contained(inner, outer):
            return (inner["x"] >= outer["x"] and inner["y"] >= outer["y"]
                    and inner["x"] + inner["width"] <= outer["x"] + outer["width"]
                    and inner["y"] + inner["height"] <= outer["y"] + outer["height"])
        if not contained(l["window"], {"x": 0, "y": 0, "width": l["designWidth"], "height": l["designHeight"]}):
            fail(rel + ": " + name + ".window must fit the design canvas")
        for part in parts:
            if part != "window" and not contained(l[part], l["window"]):
                fail(rel + ": " + name + "." + part + " must be inside the window")
        for i, a1 in enumerate(actions):
            for a2 in actions[i + 1:]:
                r1, r2 = l[a1], l[a2]
                if (r1["x"] < r2["x"] + r2["width"] and r2["x"] < r1["x"] + r1["width"]
                        and r1["y"] < r2["y"] + r2["height"] and r2["y"] < r1["y"] + r1["height"]):
                    fail(rel + ": " + name + " actions " + a1 + " and " + a2 + " must not overlap")
    m = doc.get("motion") or {}
    if m.get("durationMs", 0) <= 0 or m.get("durationMs", 0) > 1000:
        fail(rel + ": motion.durationMs must be in (0, 1000]")
    if not (0.0 < m.get("scaleFrom", 0.0) <= 1.0):
        fail(rel + ": motion.scaleFrom must be in (0, 1]")
    if m.get("captureModeDurationMs") != 0:
        fail(rel + ": captureModeDurationMs must be 0 (deterministic captures)")

    if profile == "command-card":
        spacing = doc.get("spacingRules")
        if not isinstance(spacing, list) or not spacing:
            fail(rel + ": spacingRules must be a non-empty list")
        seen_ids = set()
        for rule in spacing:
            if not isinstance(rule, dict):
                fail(rel + ": each spacing rule must be an object")
            rid = rule.get("id")
            if not isinstance(rid, str) or not rid or rid in seen_ids:
                fail(rel + ": spacing rule ids must be non-empty and unique")
            seen_ids.add(rid)
            kind = rule.get("kind")
            for layout_name in ("wide", "compact"):
                minimum = rule.get(layout_name)
                if not isinstance(minimum, int) or minimum <= 0:
                    fail(rel + ": spacing " + rid + "." + layout_name + " must be a positive integer")
            if kind == "gap":
                first, second, axis = rule.get("first"), rule.get("second"), rule.get("axis")
                if first not in parts or second not in parts or axis not in ("horizontal", "vertical"):
                    fail(rel + ": gap " + rid + " must reference two parts and a supported axis")
                for layout_name in ("wide", "compact"):
                    first_rect, second_rect = layouts[layout_name][first], layouts[layout_name][second]
                    gap = (second_rect["x"] - first_rect["x"] - first_rect["width"]
                           if axis == "horizontal"
                           else second_rect["y"] - first_rect["y"] - first_rect["height"])
                    if gap < rule[layout_name]:
                        fail(rel + ": " + layout_name + " gap " + rid + " is " + str(gap)
                             + ", expected >= " + str(rule[layout_name]))
            elif kind == "inset":
                container, child, edges = rule.get("container"), rule.get("child"), rule.get("edges")
                if container not in parts or child not in parts:
                    fail(rel + ": inset " + rid + " must reference container and child parts")
                if (not isinstance(edges, list) or not edges
                        or any(edge not in ("left", "right", "top", "bottom") for edge in edges)):
                    fail(rel + ": inset " + rid + " has unsupported edges")
                for layout_name in ("wide", "compact"):
                    outer, inner = layouts[layout_name][container], layouts[layout_name][child]
                    insets = {
                        "left": inner["x"] - outer["x"],
                        "right": outer["x"] + outer["width"] - inner["x"] - inner["width"],
                        "top": inner["y"] - outer["y"],
                        "bottom": outer["y"] + outer["height"] - inner["y"] - inner["height"],
                    }
                    for edge in edges:
                        if insets[edge] < rule[layout_name]:
                            fail(rel + ": " + layout_name + " inset " + rid + "." + edge
                                 + " is " + str(insets[edge]) + ", expected >= " + str(rule[layout_name]))
            else:
                fail(rel + ": spacing " + rid + " kind must be gap or inset")

    calibration = doc.get("engineTextScale")
    if engine_text_calibration:
        if not isinstance(calibration, dict):
            fail(rel + ": engineTextScale object required")
        for role in ("title", "data", "body", "input", "action"):
            scale = calibration.get(role)
            if not isinstance(scale, (int, float)) or not (0.0 < scale <= 1.0):
                fail(rel + ": engineTextScale." + role + " must be in (0, 1]")


def validate_screen(doc, rel):
    if doc.get("schema") != 1:
        fail(rel + ": schema must be 1")
    if not isinstance(doc.get("version"), str) or not VERSION_RE.match(doc.get("version", "")):
        fail(rel + ": version string required")
    screen = doc.get("screen") or {}
    for key in ("id", "archetype", "runtime"):
        if not isinstance(screen.get(key), str) or not screen[key]:
            fail(rel + ": screen." + key + " required")
    if not SCREEN_ID_RE.fullmatch(screen["id"]):
        fail(rel + ": screen.id must be a lower-kebab identifier")
    if screen["runtime"] not in ("production", "proof-only"):
        fail(rel + ": screen.runtime must be production or proof-only")
    if screen.get("productionHook") != (screen["runtime"] == "production"):
        fail(rel + ": screen.productionHook must derive from runtime")
    coordinate_spaces = doc.get("coordinateSpaces")
    if (not isinstance(coordinate_spaces, list) or not coordinate_spaces
            or any(not isinstance(space, str) or not space for space in coordinate_spaces)
            or len(set(coordinate_spaces)) != len(coordinate_spaces)):
        fail(rel + ": coordinateSpaces must be a non-empty unique string array")
    provenance = doc.get("provenance") or {}
    for key in ("generator", "source", "screenTemplate"):
        if not isinstance(provenance.get(key), str) or not provenance[key]:
            fail(rel + ": provenance." + key + " required")
    actions = doc.get("actions")
    if not isinstance(actions, list) or not actions:
        fail(rel + ": non-empty actions array required")
    action_ids = []
    for index, action in enumerate(actions):
        if not isinstance(action, dict):
            fail(rel + ": actions[" + str(index) + "] must be an object")
        for key in ("id", "component", "slotRole"):
            if not isinstance(action.get(key), str) or not action[key]:
                fail(rel + ": actions[" + str(index) + "]." + key + " required")
        variants = action.get("variants") or []
        if variants:
            context = action.get("variantContext")
            if not isinstance(context, str) or not context:
                fail(rel + ": action " + action["id"] + " variantContext required")
            whens = []
            for candidate in variants:
                if (not isinstance(candidate, dict)
                        or set(candidate) != {"when", "labelKey", "handler"}
                        or not isinstance(candidate.get("when"), bool)
                        or not all(isinstance(candidate.get(key), str) and candidate[key]
                                   for key in ("labelKey", "handler"))):
                    fail(rel + ": action " + action["id"]
                         + " variants must contain boolean when, labelKey, handler")
                whens.append(candidate["when"])
            if len(whens) != 2 or set(whens) != {False, True}:
                fail(rel + ": action " + action["id"]
                     + " variants must contain unique exhaustive boolean branches")
        candidates = variants or [action]
        for candidate in candidates:
            if (not isinstance(candidate, dict)
                    or not isinstance(candidate.get("handler"), str)
                    or not candidate["handler"]):
                fail(rel + ": action handler required: " + action["id"])
            if not handler_matches_runtime(candidate["handler"], screen["runtime"]):
                fail(rel + ": action handler must match the "
                     + ("proof" if screen["runtime"] == "proof-only" else "production")
                     + " runtime namespace grammar: " + action["id"])
        action_ids.append(action["id"])
    if len(set(action_ids)) != len(action_ids):
        fail(rel + ": action ids must be unique")
    labels = ((doc.get("fixture") or {}).get("labels")
              if isinstance(doc.get("fixture"), dict) else None)
    if not isinstance(labels, dict):
        fail(rel + ": fixture.labels must be an object")
    action_labels = labels.get("actions")
    if not isinstance(action_labels, dict):
        fail(rel + ": fixture.labels.actions must be an object")
    for action_id in action_ids:
        label = action_labels.get(action_id)
        if not isinstance(label, str) or not label.strip():
            fail(rel + ": fixture.labels.actions missing non-empty label for " + action_id)
    fixture_copy = labels.get("copy")
    if (not isinstance(fixture_copy, dict)
            or any(not isinstance(key, str) or not key
                   or not isinstance(value, str)
                   for key, value in fixture_copy.items())):
        fail(rel + ": fixture.labels.copy must be a string map")
    layouts = doc.get("layouts")
    if not isinstance(layouts, dict) or set(layouts) != {"wide", "compact"}:
        fail(rel + ": layouts must contain exactly wide and compact")
    for layout_name in ("wide", "compact"):
        layout = layouts[layout_name]
        if not isinstance(layout, dict):
            fail(rel + ": " + layout_name + " must be an object")
        design = layout.get("designSize")
        if (not isinstance(design, list) or len(design) != 2
                or any(not isinstance(value, int) or isinstance(value, bool) or value <= 0
                       for value in design)):
            fail(rel + ": " + layout_name + ".designSize must contain positive integers")
        regions = layout.get("regions")
        if not isinstance(regions, dict):
            fail(rel + ": " + layout_name + ".regions must be an object")
        for region_id, rect in regions.items():
            if not isinstance(region_id, str) or not region_id:
                fail(rel + ": " + layout_name + ".regions requires named rectangles")
            if (not isinstance(rect, list) or len(rect) != 4
                    or any(not isinstance(value, int) or isinstance(value, bool) for value in rect)
                    or rect[2] <= 0 or rect[3] <= 0):
                fail(rel + ": " + layout_name + ".regions." + region_id
                     + " must be an integer rectangle")
        resolved = layout.get("actions")
        if not isinstance(resolved, dict) or set(resolved) != set(action_ids):
            fail(rel + ": " + layout_name + " action geometry must cover every action")
        for action_id, action_layout in resolved.items():
            if not isinstance(action_layout, dict):
                fail(rel + ": " + layout_name + ".actions." + action_id
                     + " must be an object")
            for scalar_name in ("focusOrder", "zOrder"):
                scalar = action_layout.get(scalar_name)
                if not isinstance(scalar, int) or isinstance(scalar, bool):
                    fail(rel + ": " + layout_name + ".actions." + action_id + "."
                         + scalar_name + " must be an integer")
            coordinate_space = action_layout.get("coordinateSpace")
            if coordinate_space not in coordinate_spaces:
                fail(rel + ": " + layout_name + " action " + action_id
                     + " uses unsupported coordinateSpace " + str(coordinate_space))
            for rect_name in ("visibleRect", "hitRect"):
                rect = action_layout.get(rect_name)
                if (not isinstance(rect, list) or len(rect) != 4
                        or any(not isinstance(value, int) or isinstance(value, bool) for value in rect)
                        or rect[2] <= 0 or rect[3] <= 0):
                    fail(rel + ": " + layout_name + ".actions." + action_id + "."
                         + rect_name + " must be an integer rectangle")
            hit = action_layout["hitRect"]
            if hit[2] < MIN_ACTION_TARGET or hit[3] < MIN_ACTION_TARGET:
                fail(rel + ": " + layout_name + " action " + action_id
                     + " is below the 44x44 hit-target floor")
            if coordinate_space == "screen":
                if (hit[0] < 0 or hit[1] < 0 or hit[0] + hit[2] > design[0]
                        or hit[1] + hit[3] > design[1]):
                    fail(rel + ": " + layout_name + " action " + action_id
                         + " leaves the design canvas")


def rgba_call(value):
    # Emit the packed 0xRRGGBBAA word directly: the generated header stays
    # dependency-free (no CalypsoHdUiModel.h include needed).
    return "0x%08Xu" % int(value, 16)


